    private static void InfoRow(XGraphics gfx, double baseline, string label, string value)
    {
        Text(gfx, 345, baseline, 10, label);
        RightText(gfx, Right, baseline, 10, value);
    }

    private static double InvoiceTableHeader(XGraphics gfx, double y)
    {
        var header = new XFont(TestPdfs.FontFamily, 9.5, XFontStyleEx.Bold);
        gfx.DrawString("Pos", header, XBrushes.Black, Left, y);
        gfx.DrawString("Artikel", header, XBrushes.Black, 80, y);
        RightAligned(gfx, "Menge", header, 330, y);
        gfx.DrawString("Einheit", header, XBrushes.Black, 340, y);
        RightAligned(gfx, "Einzelpreis", header, 465, y);
        RightAligned(gfx, "Gesamt", header, Right, y);
        Rule(gfx, y + 6);
        return y + 22;
    }

    private static double InvoiceRow(XGraphics gfx, double y, (string Pos, string Article, string Quantity, string Unit, string Price, string Total) line)
    {
        Text(gfx, Left, y, 10, line.Pos);
        Text(gfx, 80, y, 10, line.Article);
        RightText(gfx, 330, y, 10, line.Quantity);
        Text(gfx, 340, y, 10, line.Unit);
        RightText(gfx, 465, y, 10, line.Price);
        RightText(gfx, Right, y, 10, line.Total);
        return y + 18;
    }

    private static void Footer(XGraphics gfx, string pageLabel)
    {
        Rule(gfx, 778);
        Text(gfx, Left, 790, 7.5, "Bio-Hof Müller · Inh. Josef Müller · Steuernummer 156/220/40817 · USt-IdNr. DE287654321");
