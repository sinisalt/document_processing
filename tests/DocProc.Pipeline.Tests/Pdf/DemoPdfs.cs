    private static byte[] Build(string title, DateTime createdAt, Action<PdfDocument> compose)
    {
        TestPdfs.EnsureFonts();
        using var document = new PdfDocument();
        var creditNote = title.StartsWith("Gutschrift", StringComparison.Ordinal);
        document.Info.Title = title;
        document.Info.Author = creditNote ? "Getränke Hoffmann GmbH" : "Bio-Hof Müller";
        document.Info.Creator = creditNote ? "GH-Faktura 11" : "Hofladen-Kasse 3.2";
        document.Info.CreationDate = createdAt;
        compose(document);
        using var stream = new MemoryStream();
        document.Save(stream, closeStream: false);
        return stream.ToArray();
    }

    private static XGraphics NewPage(PdfDocument document)
    {
        var page = document.AddPage();
        page.Size = PageSize.A4;
        return XGraphics.FromPdfPage(page);
    }

