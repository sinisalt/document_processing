    private static readonly AcknowledgementReport Rejection = new(null, null, ExternalRefStatus.Rejected, "Vendor blocked");

    private ISystemDbContextFactory Contexts => factory.Services.GetRequiredService<ISystemDbContextFactory>();

    private OutputDestination DestinationOf(Setup setup) => factory.Query(db => db.OutputDestinations.AsNoTracking().Single(d => d.Id == setup.Destination));

    [Fact]
    public async Task Two_identical_signed_callbacks_that_ran_at_the_same_time_apply_once()
    {
        var setup = await SetupAsync("Callback race");
        var destination = DestinationOf(setup);
        var now = factory.Clock.GetUtcNow();
        var report = Rejection with { ExternalId = setup.ExternalId };
        var stamp = new CallbackStamp(DateTimeOffset.FromUnixTimeSeconds(now.ToUnixTimeSeconds()), new string('a', 64));

        // What two concurrent requests (a receiver that timed out and sent the same request again) do: both read the
        // reference and pass the guard before either saves.
        await using (var first = Contexts.CreatePlatformScoped())
        await using (var second = Contexts.CreatePlatformScoped())
        {
            (await ExternalAcknowledgements.ApplyAsync(first, destination, report, AcknowledgementSources.Callback, now, Ct, stamp)).ShouldBe(AcknowledgementOutcome.Applied);
            (await ExternalAcknowledgements.ApplyAsync(second, destination, report, AcknowledgementSources.Callback, now, Ct, stamp)).ShouldBe(AcknowledgementOutcome.Applied);
            (await ExternalAcknowledgements.TrySaveAsync(first, Ct)).ShouldBeTrue();
            (await ExternalAcknowledgements.TrySaveAsync(second, Ct)).ShouldBeFalse("the reference moved since the second one read it");
        }

        // The second request applies again on what is there now, as the callback endpoint does: a replay.
        (await ExternalAcknowledgements.ApplyInOrderAsync(Contexts, destination, [report], AcknowledgementSources.Callback, now, stamp, Ct)).ShouldBe([AcknowledgementOutcome.Replayed]);
        Flags(setup.Document).ShouldHaveSingleItem().ResolvedAt.ShouldBeNull();
        factory.Query(db => db.ReviewTasks.Count(t => t.DocumentId == setup.Document && t.Kind == ReviewTaskKind.IntegrationIssue)).ShouldBe(1, "one integration issue");
        factory.Query(db => db.DocumentEvents.Count(e => e.DocumentId == setup.Document && e.EventType == "document.externally_rejected")).ShouldBe(1);
        var reference = factory.Query(db => db.DocumentExternalRefs.Single(r => r.DocumentId == setup.Document));
        reference.Status.ShouldBe(ExternalRefStatus.Rejected);
        reference.AcknowledgementVersion.ShouldBe(1);
    }

    [Theory]
    [InlineData(true)]
    [InlineData(false)]
    public async Task A_rejection_and_a_later_acceptance_that_ran_at_the_same_time_end_accepted_whichever_commits_first(bool acceptanceFirst)
    {
        var setup = await SetupAsync("Callback reject accept " + acceptanceFirst);
        var destination = DestinationOf(setup);
        var now = factory.Clock.GetUtcNow();
        var at = DateTimeOffset.FromUnixTimeSeconds(now.ToUnixTimeSeconds());
        var rejection = (Report: Rejection with { ExternalId = setup.ExternalId }, Stamp: new CallbackStamp(at.AddSeconds(-1), new string('r', 64)));
        var acceptance = (Report: new AcknowledgementReport(null, setup.ExternalId, ExternalRefStatus.Accepted, null), Stamp: new CallbackStamp(at, new string('c', 64)));
        var (winner, loser) = acceptanceFirst ? (acceptance, rejection) : (rejection, acceptance);

        await using (var won = Contexts.CreatePlatformScoped())
        await using (var lost = Contexts.CreatePlatformScoped())
        {
            (await ExternalAcknowledgements.ApplyAsync(won, destination, winner.Report, AcknowledgementSources.Callback, now, Ct, winner.Stamp)).ShouldBe(AcknowledgementOutcome.Applied);
            (await ExternalAcknowledgements.ApplyAsync(lost, destination, loser.Report, AcknowledgementSources.Callback, now, Ct, loser.Stamp)).ShouldBe(AcknowledgementOutcome.Applied);
            (await ExternalAcknowledgements.TrySaveAsync(won, Ct)).ShouldBeTrue();
            (await ExternalAcknowledgements.TrySaveAsync(lost, Ct)).ShouldBeFalse();
        }

        // Applied again: the rejection is older than the acceptance that committed, so it is not applied; the acceptance
        // is newer than the rejection that committed, so it applies and resolves what the rejection opened.
        (await ExternalAcknowledgements.ApplyInOrderAsync(Contexts, destination, [loser.Report], AcknowledgementSources.Callback, now, loser.Stamp, Ct))
            .ShouldBe([acceptanceFirst ? AcknowledgementOutcome.Replayed : AcknowledgementOutcome.Applied]);
        factory.Query(db => db.DocumentExternalRefs.Single(r => r.DocumentId == setup.Document).Status).ShouldBe(ExternalRefStatus.Accepted);
        Flags(setup.Document).ShouldAllBe(f => f.ResolvedAt != null, "no EXTERNAL_REJECTED stays open");
        Flags(setup.Document).Count.ShouldBe(acceptanceFirst ? 0 : 1);
        factory.Query(db => db.ReviewTasks.Count(t => t.DocumentId == setup.Document && t.Kind == ReviewTaskKind.IntegrationIssue && t.Status == ReviewTaskStatus.Open)).ShouldBe(0);
    }

    [Fact]
    public async Task A_signed_callback_for_one_destination_does_not_authenticate_at_another_that_holds_the_same_secret()
    {
        var a = await SetupAsync("Callback binding A");
        var b = await SetupAsync("Callback binding B");
        using var adminA = factory.TenantAdminOf(a.Tenant);
        using var adminB = factory.TenantAdminOf(b.Tenant);
        using var anonymous = factory.CreateClient();
        (await adminA.PutAsJsonAsync($"/api/v1/destinations/{a.Destination}/acknowledgements", new { callback = new { auth = "hmacSha256" } }, Ct)).StatusCode.ShouldBe(HttpStatusCode.OK);
        (await adminB.PutAsJsonAsync($"/api/v1/destinations/{b.Destination}/acknowledgements", new { callback = new { auth = "hmacSha256" } }, Ct)).StatusCode.ShouldBe(HttpStatusCode.OK);
        var secretA = (await NewSecretAsync(adminA, a.Destination)).Secret;
        (await NewSecretAsync(adminB, b.Destination)).Secret.ShouldNotBe(secretA, "the platform makes every secret, so two destinations do not share one");

        // Even when B holds A's secret (put into the store by hand) and a reference with the same receiver id, a
        // callback signed for A and replayed unchanged to B's address does not authenticate: the destination is signed.
        var referenceOfB = factory.Query(db => db.OutputDestinations.Single(d => d.Id == b.Destination).CallbackSecretRef)!;
        await factory.Services.GetRequiredService<ISecretStore>().SetAsync(referenceOfB, secretA, Ct);
        factory.Run(db => db.DocumentExternalRefs.Single(r => r.DestinationId == b.Destination).ExternalId = a.ExternalId);
        var body = $$"""{"externalId":"{{a.ExternalId}}","status":"rejected","message":"meant for A"}""";
        var signedForA = Callback(a.Destination, body, secretA, factory.Clock.GetUtcNow());
        var replayedToB = Callback(a.Destination, body, secretA, factory.Clock.GetUtcNow());
        replayedToB.RequestUri = new Uri($"/api/v1/integrations/callbacks/{b.Destination}", UriKind.Relative);
        var atA = await anonymous.SendAsync(signedForA, Ct);
        atA.StatusCode.ShouldBe(HttpStatusCode.OK, await atA.Content.ReadAsStringAsync(Ct));
        (await atA.Content.ReadFromJsonAsync<CallbackResponse>(ApiFactory.Json, Ct))!.Applied.ShouldBe(1);
        (await anonymous.SendAsync(replayedToB, Ct)).StatusCode.ShouldBe(HttpStatusCode.Unauthorized);
        Flags(b.Document).ShouldBeEmpty("nothing meant for A reaches B");

        // The signature of fix 2, over the timestamp and the body only, is refused too.
        var timestamp = factory.Clock.GetUtcNow().ToUnixTimeSeconds().ToString(CultureInfo.InvariantCulture);
        var unbound = new HttpRequestMessage(HttpMethod.Post, $"/api/v1/integrations/callbacks/{b.Destination}") { Content = new StringContent(body, Encoding.UTF8, "application/json") };
        unbound.Headers.Add(IntegrationEndpoints.TimestampHeader, timestamp);
        unbound.Headers.Add(IntegrationEndpoints.SignatureHeader, "sha256=" + Convert.ToHexStringLower(System.Security.Cryptography.HMACSHA256.HashData(Encoding.UTF8.GetBytes(secretA), Encoding.UTF8.GetBytes(timestamp + "." + body))));
        (await anonymous.SendAsync(unbound, Ct)).StatusCode.ShouldBe(HttpStatusCode.Unauthorized);
        Flags(b.Document).ShouldBeEmpty();
