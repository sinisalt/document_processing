    public async Task The_callback_secret_rotates_with_the_old_one_accepted_until_the_next_rotation_and_bearer_works_too()
    {
        var setup = await SetupAsync("Callback rotation");
        using var admin = factory.TenantAdminOf(setup.Tenant);
        using var anonymous = factory.CreateClient();
        (await admin.PutAsJsonAsync($"/api/v1/destinations/{setup.Destination}/acknowledgements", new { callback = new { auth = "bearer" } }, Ct)).StatusCode.ShouldBe(HttpStatusCode.OK);
        // The platform makes every secret: one the admin chooses is not taken (so two destinations never share one).
        (await admin.PutAsJsonAsync($"/api/v1/destinations/{setup.Destination}/callback-secret", new { secret = "chosen-by-the-admin-0123" }, Ct)).StatusCode.ShouldBe(HttpStatusCode.MethodNotAllowed);
        var first = await NewSecretAsync(admin, setup.Destination);
        first.Destination.HasPreviousCallbackSecret.ShouldBeFalse();
        var second = await NewSecretAsync(admin, setup.Destination);
        second.Destination.HasPreviousCallbackSecret.ShouldBeTrue();
        second.Secret.ShouldNotBe(first.Secret);

        // Without a mapping the body is the acknowledgement itself.
        var body = $$"""{"externalId":"{{setup.ExternalId}}","status":"accepted"}""";
        (await anonymous.SendAsync(Callback(setup.Destination, body, first.Secret, factory.Clock.GetUtcNow(), auth: "bearer"), Ct)).StatusCode.ShouldBe(HttpStatusCode.OK, "the replaced secret is still accepted");
        (await anonymous.SendAsync(Callback(setup.Destination, body, second.Secret, factory.Clock.GetUtcNow(), auth: "bearer"), Ct)).StatusCode.ShouldBe(HttpStatusCode.OK);
        var third = await NewSecretAsync(admin, setup.Destination);
        (await anonymous.SendAsync(Callback(setup.Destination, body, first.Secret, factory.Clock.GetUtcNow(), auth: "bearer"), Ct)).StatusCode.ShouldBe(HttpStatusCode.Unauthorized, "two rotations later");
        (await anonymous.SendAsync(Callback(setup.Destination, """{"status":"accepted"}""", third.Secret, factory.Clock.GetUtcNow(), auth: "bearer"), Ct)).StatusCode.ShouldBe(HttpStatusCode.UnprocessableEntity, "no id");
        factory.Query(db => db.DocumentExternalRefs.Single(r => r.DocumentId == setup.Document).Status).ShouldBe(ExternalRefStatus.Accepted);
    }

